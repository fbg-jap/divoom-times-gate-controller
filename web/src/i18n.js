const tables = { en, es };
let language = "en";
export const setLanguage = (value) => {
  language = Object.hasOwn(tables, value) ? value : "en";
};
export const getLanguage = () => language;
export function t(key, params) {
  const text = tables[language][key] ?? en[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m)) : text;
}
// Object whose values are looked up on every read, so a language change applies to module-level tables.
